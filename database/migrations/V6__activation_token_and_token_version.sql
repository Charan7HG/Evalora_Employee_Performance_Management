-- ============================================================================
-- Evalora - Migration V6 : activation tokens and JWT token version
-- ============================================================================
--
-- 1. activation_tokens : single-use activation tokens for new employee/manager
--    accounts. Only the SHA-256 hash is stored; the raw token is never persisted.
--    Tokens expire after 24 hours and are single-use only.
-- ----------------------------------------------------------------------------
CREATE TABLE activation_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL,
    token_hash    VARCHAR(64) NOT NULL,
    expires_at    TIMESTAMPTZ NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_activation_token UNIQUE (token_hash),
    CONSTRAINT fk_activation_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_activation_user ON activation_tokens (user_id);
CREATE INDEX ix_activation_expires ON activation_tokens (expires_at);

-- 2. Add token_version to users for JWT invalidation after password changes.
--    Existing accounts get token_version = 1 on first login after migration.
-- ----------------------------------------------------------------------------
ALTER TABLE users ADD COLUMN token_version BIGINT NOT NULL DEFAULT 1;

-- ----------------------------------------------------------------------------
-- 3. Seed token_version = 1 for all existing accounts (they already have
--    a version; new accounts will continue using this value until a password
--    change increments it).
-- ----------------------------------------------------------------------------
UPDATE users SET token_version = 1 WHERE token_version IS NULL;

-- ----------------------------------------------------------------------------
-- 4. Index for efficient token version validation in the JWT filter.
-- ----------------------------------------------------------------------------
CREATE INDEX ix_users_token_version ON users (token_version);

-- ----------------------------------------------------------------------------
-- 5. Helper: invalidate all unused activation tokens for a user (called
--    when resending activation email).
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION invalidate_all_unused_activation_tokens_for_user(user_id BIGINT, now TIMESTAMPTZ)
RETURNS VOID AS $$
BEGIN
    UPDATE activation_tokens
    SET updated_at = now,
        used_at = now
    WHERE user_id = activation_tokens.user_id
      AND used_at IS NULL
      AND expires_at > now;
END;
$$ LANGUAGE plpgsql;

-- ----------------------------------------------------------------------------
-- 6. Helper: check if a user has any active (unused, non-expired) activation
--    tokens. Used by HR to check pending activation status.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION has_active_activation_token(user_id BIGINT)
RETURNS BOOLEAN AS $$
DECLARE
    count INTEGER;
BEGIN
    SELECT COUNT(*)
      INTO count
      FROM activation_tokens
     WHERE user_id = activation_tokens.user_id
       AND used_at IS NULL
       AND expires_at > now();  -- Note: PostgreSQL evaluates now() at query start
    RETURN count > 0;
END;
$$ LANGUAGE plpgsql;