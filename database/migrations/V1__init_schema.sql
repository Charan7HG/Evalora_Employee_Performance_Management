-- ----------------------------------------------------------------------------
-- 1. users : login identity. The role here is the single source of truth.
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 VARCHAR(255) NOT NULL,
    password_hash         VARCHAR(100) NOT NULL,
    role                  VARCHAR(20)  NOT NULL,
    enabled               BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    last_login_at         TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_role
        CHECK (role IN ('HR', 'MANAGER', 'EMPLOYEE')),
    CONSTRAINT ck_users_failed_attempts
        CHECK (failed_login_attempts >= 0)
);

-- Case-insensitive uniqueness: "HR@Evalora.local" and "hr@evalora.local" are the same person.
CREATE UNIQUE INDEX ux_users_email_lower ON users (LOWER(email));
CREATE INDEX ix_users_role_enabled ON users (role, enabled);

-- ----------------------------------------------------------------------------
-- 2. employees : staff profile for every role (HR, MANAGER, EMPLOYEE).
--    Only users whose users.role = 'EMPLOYEE' are appraised.
--    status = soft delete / deactivation flag.
-- ----------------------------------------------------------------------------
CREATE TABLE employees (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    employee_code VARCHAR(30)  NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    department    VARCHAR(100),
    designation   VARCHAR(100),
    manager_id    BIGINT,
    joining_date  DATE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_employees_user UNIQUE (user_id),
    CONSTRAINT uq_employees_code UNIQUE (employee_code),
    CONSTRAINT fk_employees_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_employees_manager
        FOREIGN KEY (manager_id) REFERENCES employees (id),
    CONSTRAINT ck_employees_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    -- An employee can never be their own manager.
    CONSTRAINT ck_employees_not_own_manager
        CHECK (manager_id IS NULL OR manager_id <> id)
);

CREATE INDEX ix_employees_manager ON employees (manager_id);
CREATE INDEX ix_employees_status ON employees (status);
CREATE INDEX ix_employees_name_lower ON employees (LOWER(full_name));

-- ----------------------------------------------------------------------------
-- 3. password_reset_tokens : one-time tokens, only the SHA-256 hash is stored.
-- ----------------------------------------------------------------------------
CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_password_reset_token UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_password_reset_user ON password_reset_tokens (user_id);
CREATE INDEX ix_password_reset_expiry ON password_reset_tokens (expires_at);

-- ----------------------------------------------------------------------------
-- 4. kpi_master : reusable KPI catalogue. Deactivate (active = false) instead
--    of deleting, so historical data keeps a valid reference.
-- ----------------------------------------------------------------------------
CREATE TABLE kpi_master (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(150) NOT NULL,
    description       TEXT,
    category          VARCHAR(80),
    default_weightage NUMERIC(5,2),
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by        BIGINT,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_kpi_created_by
        FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_kpi_default_weight
        CHECK (default_weightage IS NULL
               OR (default_weightage > 0 AND default_weightage <= 100))
);

CREATE UNIQUE INDEX ux_kpi_master_name_lower ON kpi_master (LOWER(name));
CREATE INDEX ix_kpi_master_active ON kpi_master (active);

-- ----------------------------------------------------------------------------
-- 5. performance_cycles : one review period. Deadlines are informational
--    (soft) in v1 - workflow order is enforced, dates only drive reminders.
-- ----------------------------------------------------------------------------
CREATE TABLE performance_cycles (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     VARCHAR(150) NOT NULL,
    description              TEXT,
    start_date               DATE NOT NULL,
    end_date                 DATE NOT NULL,
    self_assessment_deadline DATE NOT NULL,
    manager_review_deadline  DATE NOT NULL,
    hr_review_deadline       DATE NOT NULL,
    status                   VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_by               BIGINT NOT NULL,
    published_at             TIMESTAMPTZ,
    completed_at             TIMESTAMPTZ,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cycle_created_by
        FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_cycle_status
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_cycle_dates
        CHECK (start_date < end_date
               AND self_assessment_deadline >= start_date
               AND self_assessment_deadline <= end_date
               AND manager_review_deadline >= self_assessment_deadline
               AND hr_review_deadline >= manager_review_deadline),
    -- A cycle's timestamps must always agree with its status.
    CONSTRAINT ck_cycle_timestamps
        CHECK (
            (status = 'DRAFT'
                AND published_at IS NULL AND completed_at IS NULL)
            OR (status = 'PUBLISHED'
                AND published_at IS NOT NULL AND completed_at IS NULL)
            OR (status = 'IN_PROGRESS'
                AND published_at IS NOT NULL AND completed_at IS NULL)
            OR (status = 'COMPLETED'
                AND published_at IS NOT NULL AND completed_at IS NOT NULL)
        )
);

CREATE UNIQUE INDEX ux_cycles_name_lower ON performance_cycles (LOWER(name));
CREATE INDEX ix_cycles_status ON performance_cycles (status);
CREATE INDEX ix_cycles_dates ON performance_cycles (start_date, end_date);

-- ----------------------------------------------------------------------------
-- 6. cycle_kpis : which KPIs a cycle uses, and their weight for that cycle.
--    weightage NULL for every row  -> average mode.
--    weightage set for every row   -> weighted mode, must total 100.00.
--    (enforced by the service layer in Phase 3B, not by the database)
-- ----------------------------------------------------------------------------
CREATE TABLE cycle_kpis (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id   BIGINT NOT NULL,
    kpi_id     BIGINT NOT NULL,
    weightage  NUMERIC(5,2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cycle_kpi_cycle
        FOREIGN KEY (cycle_id) REFERENCES performance_cycles (id),
    CONSTRAINT fk_cycle_kpi_master
        FOREIGN KEY (kpi_id) REFERENCES kpi_master (id),
    CONSTRAINT uq_cycle_kpi UNIQUE (cycle_id, kpi_id),
    CONSTRAINT ck_cycle_kpi_weight
        CHECK (weightage IS NULL OR (weightage > 0 AND weightage <= 100))
);

CREATE INDEX ix_cycle_kpis_cycle ON cycle_kpis (cycle_id);
CREATE INDEX ix_cycle_kpis_kpi ON cycle_kpis (kpi_id);

-- ----------------------------------------------------------------------------
-- 7. employee_assignments : one appraisal per employee per cycle.
--    manager_id is a snapshot of who reviewed this cycle.
-- ----------------------------------------------------------------------------
CREATE TABLE employee_assignments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id             BIGINT      NOT NULL,
    employee_id          BIGINT      NOT NULL,
    manager_id           BIGINT      NOT NULL,
    status               VARCHAR(40) NOT NULL DEFAULT 'SELF_ASSESSMENT_PENDING',
    self_submitted_at    TIMESTAMPTZ,
    manager_submitted_at TIMESTAMPTZ,
    hr_finalized_at      TIMESTAMPTZ,
    results_published_at TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assignment_cycle
        FOREIGN KEY (cycle_id) REFERENCES performance_cycles (id),
    CONSTRAINT fk_assignment_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT fk_assignment_manager
        FOREIGN KEY (manager_id) REFERENCES employees (id),
    CONSTRAINT uq_assignment_cycle_employee UNIQUE (cycle_id, employee_id),
    CONSTRAINT ck_assignment_not_own_manager
        CHECK (manager_id <> employee_id),
    CONSTRAINT ck_assignment_status
        CHECK (status IN (
            'SELF_ASSESSMENT_PENDING',
            'MANAGER_REVIEW_PENDING',
            'HR_REVIEW_PENDING',
            'COMPLETED',
            'RESULTS_PUBLISHED'
        )),
    -- Status and stage timestamps can never disagree.
    CONSTRAINT ck_assignment_timestamps
        CHECK (
            (status = 'SELF_ASSESSMENT_PENDING'
                AND self_submitted_at IS NULL
                AND manager_submitted_at IS NULL
                AND hr_finalized_at IS NULL
                AND results_published_at IS NULL)
            OR (status = 'MANAGER_REVIEW_PENDING'
                AND self_submitted_at IS NOT NULL
                AND manager_submitted_at IS NULL
                AND hr_finalized_at IS NULL
                AND results_published_at IS NULL)
            OR (status = 'HR_REVIEW_PENDING'
                AND self_submitted_at IS NOT NULL
                AND manager_submitted_at IS NOT NULL
                AND hr_finalized_at IS NULL
                AND results_published_at IS NULL)
            OR (status = 'COMPLETED'
                AND self_submitted_at IS NOT NULL
                AND manager_submitted_at IS NOT NULL
                AND hr_finalized_at IS NOT NULL
                AND results_published_at IS NULL)
            OR (status = 'RESULTS_PUBLISHED'
                AND self_submitted_at IS NOT NULL
                AND manager_submitted_at IS NOT NULL
                AND hr_finalized_at IS NOT NULL
                AND results_published_at IS NOT NULL)
        )
);

CREATE INDEX ix_assignments_cycle_status ON employee_assignments (cycle_id, status);
CREATE INDEX ix_assignments_manager_status ON employee_assignments (manager_id, status);
CREATE INDEX ix_assignments_employee ON employee_assignments (employee_id);

-- ----------------------------------------------------------------------------
-- 8. employee_kpis : frozen copy of the KPI (name, description, category,
--    weight) for one assignment. Written once, when the cycle is published,
--    so later edits to kpi_master never change history.
-- ----------------------------------------------------------------------------
CREATE TABLE employee_kpis (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id   BIGINT       NOT NULL,
    kpi_id          BIGINT       NOT NULL,
    kpi_name        VARCHAR(150) NOT NULL,
    kpi_description TEXT,
    kpi_category    VARCHAR(80),
    weightage       NUMERIC(5,2),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_employee_kpi_assignment
        FOREIGN KEY (assignment_id) REFERENCES employee_assignments (id),
    CONSTRAINT fk_employee_kpi_master
        FOREIGN KEY (kpi_id) REFERENCES kpi_master (id),
    CONSTRAINT uq_employee_kpi UNIQUE (assignment_id, kpi_id),
    CONSTRAINT ck_employee_kpi_weight
        CHECK (weightage IS NULL OR (weightage > 0 AND weightage <= 100))
);

CREATE INDEX ix_employee_kpis_assignment ON employee_kpis (assignment_id);

-- ----------------------------------------------------------------------------
-- 9. self_assessments : employee's own rating. Reference only, never scored.
-- ----------------------------------------------------------------------------
CREATE TABLE self_assessments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_kpi_id BIGINT   NOT NULL,
    rating          SMALLINT,
    comment         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_self_assessment_kpi
        FOREIGN KEY (employee_kpi_id) REFERENCES employee_kpis (id),
    CONSTRAINT uq_self_assessment UNIQUE (employee_kpi_id),
    CONSTRAINT ck_self_rating
        CHECK (rating IS NULL OR rating BETWEEN 1 AND 5)
);

-- ----------------------------------------------------------------------------
-- 10. manager_assessments : manager rating, 75% of the final score.
-- ----------------------------------------------------------------------------
CREATE TABLE manager_assessments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_kpi_id BIGINT   NOT NULL,
    manager_id      BIGINT   NOT NULL,
    rating          SMALLINT,
    comment         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_manager_assessment_kpi
        FOREIGN KEY (employee_kpi_id) REFERENCES employee_kpis (id),
    CONSTRAINT fk_manager_assessment_manager
        FOREIGN KEY (manager_id) REFERENCES employees (id),
    CONSTRAINT uq_manager_assessment UNIQUE (employee_kpi_id),
    CONSTRAINT ck_manager_rating
        CHECK (rating IS NULL OR rating BETWEEN 1 AND 5)
);

CREATE INDEX ix_manager_assessments_manager ON manager_assessments (manager_id);

-- ----------------------------------------------------------------------------
-- 11. hr_assessments : HR rating, 25% of the final score.
-- ----------------------------------------------------------------------------
CREATE TABLE hr_assessments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_kpi_id BIGINT   NOT NULL,
    hr_id           BIGINT   NOT NULL,
    rating          SMALLINT,
    comment         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_hr_assessment_kpi
        FOREIGN KEY (employee_kpi_id) REFERENCES employee_kpis (id),
    CONSTRAINT fk_hr_assessment_user
        FOREIGN KEY (hr_id) REFERENCES users (id),
    CONSTRAINT uq_hr_assessment UNIQUE (employee_kpi_id),
    CONSTRAINT ck_hr_rating
        CHECK (rating IS NULL OR rating BETWEEN 1 AND 5)
);

CREATE INDEX ix_hr_assessments_user ON hr_assessments (hr_id);

-- ----------------------------------------------------------------------------
-- 12. performance_results : one official result per assignment.
--     DRAFT      = HR finalised the score, not visible to employee/manager yet.
--     PUBLISHED  = visible, immutable forever.
-- ----------------------------------------------------------------------------
CREATE TABLE performance_results (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id    BIGINT       NOT NULL,
    overall_score    NUMERIC(4,2) NOT NULL,
    grade            VARCHAR(30)  NOT NULL,
    calculation_mode VARCHAR(10)  NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    computed_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at     TIMESTAMPTZ,
    published_by     BIGINT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_result_assignment
        FOREIGN KEY (assignment_id) REFERENCES employee_assignments (id),
    CONSTRAINT fk_result_published_by
        FOREIGN KEY (published_by) REFERENCES users (id),
    CONSTRAINT uq_result_assignment UNIQUE (assignment_id),
    CONSTRAINT ck_result_score
        CHECK (overall_score BETWEEN 1.00 AND 5.00),
    CONSTRAINT ck_result_grade
        CHECK (grade IN ('OUTSTANDING', 'EXCELLENT', 'VERY_GOOD',
                         'GOOD', 'NEEDS_IMPROVEMENT', 'UNSATISFACTORY')),
    CONSTRAINT ck_result_mode
        CHECK (calculation_mode IN ('WEIGHTED', 'AVERAGE')),
    CONSTRAINT ck_result_status
        CHECK (status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_result_publish_fields
        CHECK (
            (status = 'DRAFT'
                AND published_at IS NULL AND published_by IS NULL)
            OR (status = 'PUBLISHED'
                AND published_at IS NOT NULL AND published_by IS NOT NULL)
        )
);

CREATE INDEX ix_results_status ON performance_results (status);
CREATE INDEX ix_results_published_at ON performance_results (published_at);

-- ----------------------------------------------------------------------------
-- 13. performance_result_items : frozen per-KPI breakdown of a result.
--     This is the permanent historical record. It stores copies (not joins)
--     of the KPI name, weight, ratings and comments, so renaming a KPI or
--     editing a cycle later cannot change a published result.
-- ----------------------------------------------------------------------------
CREATE TABLE performance_result_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id       BIGINT       NOT NULL,
    employee_kpi_id BIGINT       NOT NULL,
    kpi_name        VARCHAR(150) NOT NULL,
    weightage       NUMERIC(5,2),
    self_rating     SMALLINT,
    self_comment    TEXT,
    manager_rating  SMALLINT     NOT NULL,
    manager_comment TEXT,
    hr_rating       SMALLINT     NOT NULL,
    hr_comment      TEXT,
    final_score     NUMERIC(4,2) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_result_item_result
        FOREIGN KEY (result_id) REFERENCES performance_results (id),
    CONSTRAINT fk_result_item_kpi
        FOREIGN KEY (employee_kpi_id) REFERENCES employee_kpis (id),
    CONSTRAINT uq_result_item UNIQUE (result_id, employee_kpi_id),
    CONSTRAINT ck_result_item_self_rating
        CHECK (self_rating IS NULL OR self_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_result_item_manager_rating
        CHECK (manager_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_result_item_hr_rating
        CHECK (hr_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_result_item_final_score
        CHECK (final_score BETWEEN 1.00 AND 5.00),
    CONSTRAINT ck_result_item_weight
        CHECK (weightage IS NULL OR (weightage > 0 AND weightage <= 100))
);

CREATE INDEX ix_result_items_result ON performance_result_items (result_id);
