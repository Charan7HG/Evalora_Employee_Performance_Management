-- ============================================================================
-- Evalora - Employee Performance Management System
-- Migration V2 : reporting-manager assignment history
--
-- V1 stores only the current manager in employees.manager_id, which would be
-- overwritten on reassignment. Phase 3B4 requires history, so every reporting
-- line is recorded here as an append-only row:
--   effective_to IS NULL  -> the current assignment
--   effective_to set      -> a closed (historical) assignment
--
-- This table is NOT the appraisal table. employee_assignments (V1) remains the
-- per-cycle review assignment.
--
-- Never edit V1. Add V3, V4... for later changes.
-- ============================================================================

CREATE TABLE employee_manager_assignments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    BIGINT      NOT NULL,
    manager_id     BIGINT      NOT NULL,
    assigned_by    BIGINT,
    effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    effective_to   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ema_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT fk_ema_manager
        FOREIGN KEY (manager_id) REFERENCES employees (id),
    -- The HR user who performed the assignment. Kept if that user row is
    -- removed, because history matters more than the operator reference.
    CONSTRAINT fk_ema_assigned_by
        FOREIGN KEY (assigned_by) REFERENCES users (id) ON DELETE SET NULL,
    -- A person can never report to themselves.
    CONSTRAINT ck_ema_not_own_manager
        CHECK (employee_id <> manager_id),
    -- A closed period must be non-empty.
    CONSTRAINT ck_ema_effective_period
        CHECK (effective_to IS NULL OR effective_to > effective_from)
);

-- At most one current manager per employee. This is the database-level
-- guarantee behind "an employee must not have multiple active assignments".
CREATE UNIQUE INDEX uq_ema_active_employee
    ON employee_manager_assignments (employee_id)
    WHERE effective_to IS NULL;

CREATE INDEX ix_ema_employee_history
    ON employee_manager_assignments (employee_id, effective_from);

CREATE INDEX ix_ema_manager
    ON employee_manager_assignments (manager_id);
